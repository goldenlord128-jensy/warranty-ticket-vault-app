package com.example.warrantyvault

import android.content.Context
import android.content.Intent
import android.graphics.Paint
import android.graphics.pdf.PdfDocument
import androidx.core.content.FileProvider
import java.io.File
import java.io.FileOutputStream

class PdfExporter(private val context: Context) {

    fun exportClaimPdf(item: VaultItem) {
        val document = PdfDocument()
        val pageInfo = PdfDocument.PageInfo.Builder(595, 842, 1).create() // Standard A4 Size
        val page = document.startPage(pageInfo)
        val canvas = page.canvas
        val paint = Paint()

        // Document Title Header
        paint.textSize = 20f
        paint.isFakeBoldText = true
        canvas.drawText("WARRANTY CLAIM REPORT", 50f, 60f, paint)

        paint.textSize = 12f
        paint.isFakeBoldText = false
        canvas.drawText("Generated by Warranty Vault", 50f, 85f, paint)

        // Divider Line
        canvas.drawLine(50f, 100f, 545f, 100f, paint)

        // Draw Structured Fields
        var y = 140f
        val lineSpacing = 35f

        fun drawField(label: String, value: String) {
            paint.isFakeBoldText = true
            canvas.drawText("$label:", 50f, y, paint)
            paint.isFakeBoldText = false
            canvas.drawText(value, 200f, y, paint)
            y += lineSpacing
        }

        drawField("Item / Policy", item.title)
        drawField("Brand / Provider", item.brand)
        drawField("Model / Policy ID", item.modelNumber)
        drawField("Purchase Date", item.purchaseDate)
        drawField("Warranty Duration", "${item.warrantyMonths} Months")
        drawField("Price Paid", "$${item.price}")

        // Expiration Status Details
        val expiration = ExpirationHelper.getExpirationInfo(item.purchaseDate, item.warrantyMonths)
        drawField("Coverage Status", expiration.displayText)

        // Footer Section
        canvas.drawLine(50f, y + 20f, 545f, y + 20f, paint)
        paint.textSize = 10f
        canvas.drawText("This official summary is compiled locally via Warranty Vault.", 50f, y + 50f, paint)

        document.finishPage(page)

        // Save PDF to cache directory & launch share sheet
        val pdfFile = File(context.cacheDir, "Warranty_Claim_${item.modelNumber}.pdf")
        try {
            document.writeTo(FileOutputStream(pdfFile))
            document.close()
            sharePdf(pdfFile)
        } catch (e: Exception) {
            e.printStackTrace()
        }
    }

    private fun sharePdf(file: File) {
        val uri = FileProvider.getUriForFile(
            context,
            "${context.packageName}.provider",
            file
        )

        val intent = Intent(Intent.ACTION_SEND).apply {
            type = "application/pdf"
            putExtra(Intent.EXTRA_STREAM, uri)
            addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
        }

        context.startActivity(Intent.createChooser(intent, "Share Warranty Claim PDF"))
    }
}